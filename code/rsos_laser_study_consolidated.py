# ============================================================
# 8. CORRELATED THERMAL-LIKE PHASE SCREEN
# ============================================================

def generate_phase_screen(
    phi0,
    rng
):
    """
    Generate one independent spatially correlated phase screen.
    """

    if np.isclose(
        phi0,
        0.0
    ):
        return np.zeros(
            (N, N)
        )

    noise = rng.normal(
        loc=0.0,
        scale=1.0,
        size=(N, N)
    )

    eta = gaussian_filter(
        noise,
        sigma=FILTER_SIGMA_PIXELS,
        mode="reflect"
    )

    eta = (
        eta
        - np.mean(eta)
    )

    sigma_eta = np.std(
        eta
    )

    M = np.exp(
        -(X**2 + Y**2)
        / pz**2
    )

    phase = (
        phi0
        * M
        * eta
        / sigma_eta
    )

    return phase


# ============================================================
# 9. SIMULATE ONE PERTURBED IMAGE
# ============================================================

def simulate_on(
    phi0,
    rng
):
    """
    Apply one phase perturbation and propagate the beam.
    """

    phase = generate_phase_screen(
        phi0,
        rng
    )

    A_on = (
        A0
        * np.exp(
            1j * phase
        )
    )

    U_on = propagate(
        A_on
    )

    I_on_raw = (
        np.abs(U_on)**2
    )

    I_on = (
        I_on_raw
        / I_REFERENCE
    )

    return (
        I_on,
        phase
    )


# ============================================================
# 10. TRANSVERSE PROFILE
# ============================================================

def transverse_profile(
    image,
    half_width=STRIP_HALF_WIDTH
):
    """
    Horizontal transverse profile averaged over a narrow
    strip centred on the beam axis.
    """

    ny, nx = image.shape

    centre_y = (
        ny // 2
    )

    strip = image[
        centre_y-half_width:
        centre_y+half_width+1,
        :
    ]

    return np.mean(
        strip,
        axis=0
    )


# ============================================================
# 11. GAUSSIAN PROFILE MODEL
# ============================================================

def gaussian_profile(
    xcoord,
    amplitude,
    x0,
    width,
    background
):
    """
    Gaussian transverse intensity profile:

    I(x) = A exp[-2 (x-x0)^2/w^2] + B
    """

    return (
        amplitude
        * np.exp(
            -2.0
            * (xcoord - x0)**2
            / width**2
        )
        + background
    )


# ============================================================
# 12. GAUSSIAN FIT AND DEPARTURE METRIC
# ============================================================

def fit_gaussian(
    profile
):
    """
    Fit Gaussian transverse profile and calculate residuals
    and normalized Gaussian-departure metric epsilon_G.
    """

    amplitude_guess = np.max(
        profile
    )

    x0_guess = x[
        np.argmax(
            profile
        )
    ]

    width_guess = w0

    background_guess = np.min(
        profile
    )

    p0 = [
        amplitude_guess,
        x0_guess,
        width_guess,
        background_guess
    ]

    lower_bounds = [
        0.0,
        -Lx/4,
        1e-4,
        -0.1
    ]

    upper_bounds = [
        2.0,
        Lx/4,
        Lx/2,
        0.2
    ]

    try:

        popt, _ = curve_fit(
            gaussian_profile,
            x,
            profile,
            p0=p0,
            bounds=(
                lower_bounds,
                upper_bounds
            ),
            maxfev=30000
        )

        fitted = gaussian_profile(
            x,
            *popt
        )

    except Exception:

        popt = np.array([
            np.nan,
            np.nan,
            np.nan,
            np.nan
        ])

        fitted = np.full_like(
            profile,
            np.nan
        )

    residual = (
        profile
        - fitted
    )

    if np.any(
        ~np.isfinite(residual)
    ):

        epsilon_G = np.nan

    else:

        denominator = np.sum(
            profile**2
        )

        epsilon_G = np.sqrt(
            np.sum(
                residual**2
            )
            / denominator
        )

    return (
        fitted,
        popt,
        residual,
        epsilon_G
    )


# ============================================================
# 13. STANDARDIZED RESIDUAL
# ============================================================

def standardize_residual(
    residual
):
    """
    Centre residual and divide by its standard deviation.
    """

    r = np.asarray(
        residual,
        dtype=float
    )

    r = r[
        np.isfinite(r)
    ]

    if len(r) < 10:
        return None

    r = (
        r
        - np.mean(r)
    )

    sigma = np.std(
        r,
        ddof=1
    )

    if sigma < 1e-14:
        return None

    return (
        r / sigma
    )


# ============================================================
# 14. NORMALIZED AUTOCORRELATION
# ============================================================

def normalized_autocorrelation(
    residual
):
    """
    Positive-lag normalized autocorrelation of a 1-D residual.
    """

    r = np.asarray(
        residual,
        dtype=float
    )

    r = (
        r
        - np.mean(r)
    )

    if np.std(r) < 1e-14:
        return None

    corr = np.correlate(
        r,
        r,
        mode="full"
    )

    corr = corr[
        len(r)-1:
    ]

    if corr[0] == 0:
        return None

    corr = (
        corr
        / corr[0]
    )

    return corr


# ============================================================
# 15. CORRELATION LENGTH
# ============================================================

def correlation_length(
    rho
):
    """
    Estimate correlation length at first crossing of 1/e.

    Linear interpolation is used between adjacent lag samples.
    """

    if rho is None:
        return np.nan

    threshold = (
        CORRELATION_THRESHOLD
    )

    below = np.where(
        rho <= threshold
    )[0]

    if len(below) == 0:
        return np.nan

    i = below[0]

    if i == 0:
        return 0.0

    y1 = rho[i-1]
    y2 = rho[i]

    x1 = (
        (i-1)
        * dx
    )

    x2 = (
        i
        * dx
    )

    if np.isclose(
        y2,
        y1
    ):
        lc = x2

    else:

        lc = (
            x1
            +
            (threshold-y1)
            * (x2-x1)
            / (y2-y1)
        )

    return (
        lc * 1e3
    )  # mm


# ============================================================
# 16. PROBABILITY MODEL FITTING
#
# Candidate models for signed residuals:
#
# Normal
# Student-t
# Generalized Normal
# ============================================================

def information_criteria(
    logL,
    n_params,
    n
):
    """
    AIC and BIC.
    """

    AIC = (
        2*n_params
        - 2*logL
    )

    BIC = (
        n_params*np.log(n)
        - 2*logL
    )

    return (
        AIC,
        BIC
    )


def fit_probability_models(
    data
):
    """
    Fit candidate distributions to ONE realization.

    This is intentionally performed realization-by-realization
    instead of concatenating all profiles into one enormous
    pseudo-independent sample.
    """

    output = {}


    # --------------------------------------------------------
    # Normal
    # --------------------------------------------------------

    params_n = norm.fit(
        data
    )

    logpdf = norm.logpdf(
        data,
        *params_n
    )

    logL = np.sum(
        logpdf
    )

    AIC, BIC = information_criteria(
        logL,
        2,
        len(data)
    )

    output["Normal"] = {
        "AIC": AIC,
        "BIC": BIC,
        "parameters": params_n
    }


    # --------------------------------------------------------
    # Student-t
    # --------------------------------------------------------

    params_t = t.fit(
        data
    )

    logpdf = t.logpdf(
        data,
        *params_t
    )

    logL = np.sum(
        logpdf
    )

    AIC, BIC = information_criteria(
        logL,
        3,
        len(data)
    )

    output["Student-t"] = {
        "AIC": AIC,
        "BIC": BIC,
        "parameters": params_t
    }


    # --------------------------------------------------------
    # Generalized Normal
    # --------------------------------------------------------

    params_g = gennorm.fit(
        data
    )

    logpdf = gennorm.logpdf(
        data,
        *params_g
    )

    logL = np.sum(
        logpdf
    )

    AIC, BIC = information_criteria(
        logL,
        3,
        len(data)
    )

    output["Generalized Normal"] = {
        "AIC": AIC,
        "BIC": BIC,
        "parameters": params_g
    }

    return output


